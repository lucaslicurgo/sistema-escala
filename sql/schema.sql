-- ============================================================
-- Escala & Banco de Horas — schema para rodar no Supabase
-- Cole e execute no "SQL Editor" do projeto Supabase.
-- ============================================================

-- Cada pessoa tem a própria conta (Supabase Auth) e só vê os próprios dados.
-- Configurações e feriados padrão são criados pelo app no cadastro.

-- 1) Configurações (chave → valor, por pessoa)
create table if not exists configuracoes (
  user_id uuid not null references auth.users(id) on delete cascade,
  chave   text not null,
  valor   text not null,
  primary key (user_id, chave)
);

-- 2) Feriados (datas trabalhadas antes de fins de semana)
create table if not exists feriados (
  id      bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  data    date not null,
  nome    text not null,
  constraint feriados_user_data_key unique (user_id, data)
);

-- 3) Registros de ponto (um por pessoa por dia)
--    entrada/saída/pausa_inicio salvos como "HH:MM" (texto) — a saída pode ser
--    depois da meia-noite, o sistema entende a virada. Saída vazia = dia em aberto.
create table if not exists registros (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references auth.users(id) on delete cascade,
  data         date not null,
  entrada      text not null,          -- ex.: "08:00"
  saida        text,                   -- ex.: "23:30" (vazio enquanto o dia está aberto)
  pausa_min    int  not null default 0, -- minutos de pausa/almoco
  pausa_inicio text,                   -- "HH:MM" de uma pausa em andamento
  observacao   text,
  criado_em    timestamptz not null default now(),
  constraint registros_user_data_key unique (user_id, data)
);

-- 4) Compensações, abonos e folgas usadas
--    tipo: "compensacao" (dia inteiro), "abono" (horas_min), "folga"
create table if not exists compensacoes (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  data       date not null,
  tipo       text not null check (tipo in ('compensacao', 'abono', 'folga')),
  horas_min  int  not null default 0, -- usado só no abono (ex.: 120 = 2h)
  observacao text,
  criado_em  timestamptz not null default now()
);
create index if not exists compensacoes_user_data_idx on compensacoes (user_id, data);

-- ------------------------------------------------------------
-- Segurança: bloqueia acesso anônimo via API pública do Supabase.
-- O sistema usa a chave service_role no servidor e passa normal.
-- ------------------------------------------------------------
alter table configuracoes enable row level security;
alter table feriados      enable row level security;
alter table registros     enable row level security;
alter table compensacoes  enable row level security;
