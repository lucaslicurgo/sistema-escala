-- 1) Configurações (chave → valor)
create table if not exists configuracoes (
  chave text primary key,
  valor text not null
);

-- 2) Feriados (datas trabalhadas antes de fins de semana)
create table if not exists feriados (
  id   bigint generated by default as identity primary key,
  data date not null unique,
  nome text not null
);

-- 3) Registros de ponto (um por dia)
--    entrada/saída salvos como "HH:MM" (texto) — a saída pode ser
--    depois da meia-noite, o sistema entende a virada.
create table if not exists registros (
  id         bigint generated by default as identity primary key,
  data       date not null unique,
  entrada    text not null,          -- ex.: "08:00"
  saida      text not null,          -- ex.: "23:30"
  pausa_min  int  not null default 0, -- minutos de pausa/almoco
  observacao text,
  criado_em  timestamptz not null default now()
);

-- 4) Compensações, abonos e folgas usadas
--    tipo: "compensacao" (dia inteiro), "abono" (horas_min), "folga"
create table if not exists compensacoes (
  id         bigint generated by default as identity primary key,
  data       date not null,
  tipo       text not null check (tipo in ('compensacao', 'abono', 'folga')),
  horas_min  int  not null default 0, -- usado só no abono (ex.: 120 = 2h)
  observacao text,
  criado_em  timestamptz not null default now()
);

